<!-- JAVASCRIPT: SMOOTH INFINITE LOOP + DRAG TO SCROLL -->
<script>
    (function() {
        const section = document.getElementById('social-media-posts-section');
        if (!section) return;

        const wrapper = section.querySelector('#social-media-wrapper');
        const track = section.querySelector('#social-media-track');
        if (!wrapper || !track) return;

        const originalSlides = Array.from(track.querySelectorAll('.social-slide'));
        const totalSlides = originalSlides.length;
        if (totalSlides === 0) return;

        const clonesBefore = Math.min(3, totalSlides);
        const clonesAfter = Math.min(3, totalSlides);

        let currentIndex = 0;
        let isMouseDragging = false;
        let isDragged = false; // Membedakan geser vs klik
        let mouseStartX = 0;
        let mouseStartScrollLeft = 0;
        const defaultSnapType = 'x mandatory';

        function getSlideStep() {
            const slide = track.querySelector('.social-slide');
            return slide.offsetWidth + 24; // 24px adalah gap-6
        }

        function createClones() {
            track.querySelectorAll('.social-clone').forEach(clone => clone.remove());

            for (let i = clonesBefore - 1; i >= 0; i--) {
                const clone = originalSlides[(totalSlides - 1 - i + totalSlides) % totalSlides].cloneNode(true);
                clone.classList.add('social-clone');
                track.insertBefore(clone, track.firstChild);
            }

            for (let i = 0; i < clonesAfter; i++) {
                const clone = originalSlides[i % totalSlides].cloneNode(true);
                clone.classList.add('social-clone');
                track.appendChild(clone);
            }
        }

        function getScrollPositionForIndex(index) {
            const step = getSlideStep();
            return (index + clonesBefore) * step;
        }

        function getIndexFromScrollPosition(scrollLeft) {
            const step = getSlideStep();
            const rawIndex = Math.round(scrollLeft / step) - clonesBefore;
            return ((rawIndex % totalSlides) + totalSlides) % totalSlides;
        }

        function handleScrollReset() {
            const step = getSlideStep();
            const oneSetWidth = totalSlides * step; // Total lebar 1 set gambar asli
            const maxScroll = track.scrollWidth - wrapper.clientWidth; // Titik paling ujung kanan
            const currentScroll = wrapper.scrollLeft;
            
            // Jika sudah mencapai batas PALING KIRI (mendekati 0px)
            if (currentScroll <= 2) {
                // Lompat ke kanan sejauh 1 set gambar asli
                wrapper.scrollLeft = currentScroll + oneSetWidth;
                currentIndex = totalSlides - 1; 
            } 
            // Jika sudah mencapai batas PALING KANAN (maxScroll)
            else if (currentScroll >= maxScroll - 2) {
                // Lompat ke kiri sejauh 1 set gambar asli
                wrapper.scrollLeft = currentScroll - oneSetWidth;
                currentIndex = 0; 
            } else {
                // Perbarui index saat user berhenti di slide yang valid
                const newIndex = getIndexFromScrollPosition(currentScroll);
                if (newIndex !== currentIndex) {
                    currentIndex = newIndex;
                }
            }
        }

        // --- DRAG TO SCROLL ---
        wrapper.addEventListener('pointerdown', (e) => {
            // Hanya aktif jika mouse dan klik KIRI (e.button === 0)
            if (e.pointerType !== 'mouse' || e.button !== 0) return; 

            isMouseDragging = true;
            isDragged = false; // Reset flag drag
            mouseStartX = e.clientX;
            mouseStartScrollLeft = wrapper.scrollLeft;
            wrapper.style.scrollSnapType = 'none'; // Matikan snap sementara saat drag
            wrapper.classList.add('cursor-grabbing');
        });

        window.addEventListener('pointermove', (e) => {
            if (!isMouseDragging) return;
            const dx = e.clientX - mouseStartX;
            wrapper.scrollLeft = mouseStartScrollLeft - dx;
            e.preventDefault(); // Mencegah teks ter-select

            // Jika gerakan melebihi 5px, tandai sebagai "sedang drag", bukan klik
            if (Math.abs(dx) > 5) {
                isDragged = true;
            }
        });

        window.addEventListener('pointerup', (e) => {
            if (!isMouseDragging) return;
            isMouseDragging = false;
            wrapper.style.scrollSnapType = defaultSnapType; // Nyalakan kembali snap
            wrapper.classList.remove('cursor-grabbing');
            handleScrollReset(); // Reset posisi jika berada di area klon
        });

        // Mencegah link terbuka jika pengguna melakukan "geser" (drag), bukan "klik"
        wrapper.addEventListener('click', (e) => {
            let target = e.target.closest('a');
            if (target && isDragged) {
                e.preventDefault();
                e.stopPropagation();
                isDragged = false; // Reset untuk klik selanjutnya yang sah
            }
        });

        track.addEventListener('dragstart', (e) => e.preventDefault());

        let isScrolling = false;
        wrapper.addEventListener('scroll', () => {
            if (isScrolling) return;
            isScrolling = true;
            handleScrollReset(); // Memastikan loop saat scroll manual
            isScrolling = false;
        });

        let resizeTimeout;
        window.addEventListener('resize', () => {
            clearTimeout(resizeTimeout);
            resizeTimeout = setTimeout(() => {
                createClones();
                wrapper.scrollTo({ left: getScrollPositionForIndex(currentIndex), behavior: 'auto' });
            }, 150);
        });

        // INISIALISASI
        createClones();
        const initialIndex = 0;
        wrapper.scrollTo({ left: getScrollPositionForIndex(initialIndex), behavior: 'auto' });
        currentIndex = initialIndex;

    })();
</script>